package org.example;

public class Responsable {
    public String id;
    public String nombre;
    public String area; 
    public boolean activo;

    public Responsable(String id, String nombre, String area, boolean activo) {
        this.id = id;
        this.nombre = nombre;
        this.area = area;
        this.activo = activo;
    }
}
